import { chromium, expect } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
const base = process.env.ADMIN_UI_URL || 'http://127.0.0.1:45682';
const out = resolve(process.env.ADMIN_EVIDENCE_DIR || '../.impeccable/review');
await mkdir(out, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined });
const report = { errors: [], writes: [], checks: [] };
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, colorScheme: 'light', extraHTTPHeaders: { 'X-Requested-With': 'motd-smoke' } });
  const session = await context.request.get(base + '/preview-session');
  expect(await session.text()).toContain('synthetic');
  for (const [name, content] of [['motd', '&WWelcome to the Wyldlands&n\n\n&cA synthetic welcome for a disposable preview world.&n\n\nRead NEWS for the latest changes. Type HELP to find your feet.\n'], ['imotd', '&YWelcome back, immortals.&n\n\nA synthetic staff welcome. Check the logs before opening the world.\n']]) {
    const url = base + '/admin/files/tedit/content?path=' + name;
    const saved = await context.request.get(url);
    expect(saved.status()).toBe(200);
    expect((await context.request.put(url, { headers: { 'If-Match': saved.headers().etag }, data: { content } })).status()).toBe(200);
    await new Promise(r => setTimeout(r, 500));
  }
  const page = await context.newPage();
  page.on('pageerror', e => report.errors.push(e.stack || e.message));
  page.on('request', r => { if (r.method() === 'PUT' && r.url().includes('/files/tedit/content')) report.writes.push({ url: r.url(), etag: r.headers()['if-match'] }); });
  await page.goto(base + '/admin/');
  await page.locator('main').getByRole('link', { name: /MOTD/ }).click();
  const editor = page.locator('#motd-draft');
  await expect(editor).toHaveValue(/Welcome/);
  await page.getByRole('button', { name: 'Discord block', exact: true }).click();
  await expect(page.getByLabel('Discord invite', { exact: true })).toHaveValue('');
  await page.getByLabel('Discord invite', { exact: true }).fill('https://discord.gg/disposable-preview');
  await page.getByRole('button', { name: 'Insert Discord block', exact: true }).click();
  await page.getByRole('button', { name: 'Gossip notice', exact: true }).click();
  await expect(editor).toHaveValue(/What's said on gossip/);
  const draft = await editor.inputValue();
  await page.getByRole('tab', { name: 'Immortal MOTD', exact: true }).click();
  await expect(editor).toHaveValue(/immortals/);
  await editor.fill('&YImmortal draft stays here&n\n');
  await page.getByRole('tab', { name: /^MOTD/ }).click();
  await expect(editor).toHaveValue(draft);
  await editor.fill('x'.repeat(2401));
  await expect(page.getByRole('button', { name: 'Save MOTD', exact: true })).toBeDisabled();
  await editor.fill(draft);
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: resolve(out, 'desktop.png'), fullPage: true });
  await page.getByRole('button', { name: 'Save MOTD', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Save MOTD', exact: true })).toBeDisabled();
  report.checks.push('dashboard entry, invite prompt, snippets, independent drafts, byte limit, real If-Match save');
  await page.waitForTimeout(1000);
  const url = base + '/admin/files/tedit/content?path=motd';
  const read = await context.request.get(url);
  const current = await read.json();
  expect(read.status()).toBe(200);
  const changed = await context.request.put(url, { headers: { 'If-Match': read.headers().etag }, data: { content: current.content + '\nSaved by another editor.\n' } });
  expect(changed.status()).toBe(200);
  await editor.fill(draft + '\nMy unsaved line.\n');
  await page.getByRole('button', { name: 'Save MOTD', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Someone else saved this message first' })).toBeVisible();
  await expect(editor).toHaveValue(/My unsaved line/);
  await expect(page.getByLabel('Saved copy compared with your draft')).toContainText('Saved by another editor.');
  await page.waitForTimeout(4000);
  await page.locator('section[role=alert]').scrollIntoViewIfNeeded();
  await page.screenshot({ path: resolve(out, 'conflict.png'), fullPage: true });
  report.checks.push('real stale-ETag 412 keeps draft and shows diff');
  page.once('dialog', d => d.accept());
  await page.getByRole('button', { name: 'Load saved copy', exact: true }).last().click();
  await expect(editor).toHaveValue(/Saved by another editor/);
  page.once('dialog', d => d.dismiss());
  await page.getByRole('link', { name: 'Dashboard', exact: true }).first().click();
  await expect(page).toHaveURL(/\/admin\/staff\/motd$/);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByLabel('Preview width').selectOption('40');
  await page.waitForTimeout(4000);
  await page.locator('main').evaluate(el => el.scrollTop = 0);
  await page.screenshot({ path: resolve(out, 'mobile.png'), fullPage: true });
  await page.getByRole('region', { name: 'Terminal preview, 40 columns' }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: resolve(out, 'mobile-preview.png'), fullPage: true });
  await page.getByRole('tab', { name: /Immortal MOTD/ }).click();
  await expect(editor).toHaveValue('&YImmortal draft stays here&n\n');
  await page.getByRole('region', { name: 'Terminal preview, 40 columns' }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: resolve(out, 'mobile-immortal.png'), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  expect(report.writes.every(w => !!w.etag)).toBeTruthy();
  expect(report.errors).toEqual([]);
  report.checks.push('navigation guard, mobile tabs, 40-column preview, no overflow or runtime errors');
  console.log('PASS MOTD browser workflow');
} finally {
  await writeFile(resolve(out, 'motd-report.json'), JSON.stringify(report, null, 2));
  await browser.close();
}
