type gate struct {
	level    int
	position int
	source   string
}

// orderRow is a single cmd_info[] entry in source order, for the prefix
// resolution table (R2d). seq is 1-based to match how the C table reads.
type orderRow struct {
	seq  int
	name string
	// level only — prefix resolution (interpreter.c:910-911) filters by
	// minimum_level DURING the scan; it does not consult position.
	level int
}

var cRowPattern = regexp.MustCompile(`^\s*\{\s*"([^"]+)"\s*,\s*(POS_\w+|0)\s*,\s*[^,]+,\s*([^,]+),`)

