package drawcoverage

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

// Generated report filenames.
const (
	InventoryFile = "draw-inventory.tsv"
	CoverageFile  = "draw-coverage.tsv"
	SummaryFile   = "draw-coverage-summary.txt"
)

const header = "# Generated by cmd/dp-draw-coverage. Do not edit by hand.\n"

// SiteCoverage is the draw-reach verdict for one C draw call site.
type SiteCoverage struct {
	Site           DrawSite
	DrawCount      int64
	Seed1DrawCount int64
	Scenarios      []string
	Seed1Scenarios []string
	Seeds          []int
}

// Reached reports whether any verified capture executed this draw site.
func (s SiteCoverage) Reached() bool { return s.DrawCount > 0 }

// ReachedSeed1 reports whether any verified seed-1 capture executed this site.
func (s SiteCoverage) ReachedSeed1() bool { return s.Seed1DrawCount > 0 }

// Report is the draw-site coverage of one C binary by one attributed census run.
type Report struct {
	Sites         []SiteCoverage
	InternalCalls []DrawSite
	PairsIncluded int
	Seed1Included int
	Seeds         []int
	Exclusions    []Exclusion
	TotalDraws    int64
	Seed1Draws    int64
}

// Totals summarizes overall draw-site reach.
type Totals struct {
	Sites        int
	ReachedAll   int
	ReachedSeed1 int
	TotalDraws   int64
	Seed1Draws   int64
}

// FileRollup summarizes draw-site reach for one C source file.
type FileRollup struct {
	File         string
	Sites        int
	ReachedAll   int
	ReachedSeed1 int
	Draws        int64
}

// Compute joins the binary call-site inventory with verified captures.
func Compute(inventory []DrawSite, internal []DrawSite, captures []Capture, exclusions []Exclusion) *Report {
	r := &Report{
		InternalCalls: append([]DrawSite(nil), internal...),
		Exclusions:    append([]Exclusion(nil), exclusions...),
	}
	idxBySite := make(map[string]int, len(inventory))
	scSets := make([]map[string]bool, len(inventory))
	scSeed1Sets := make([]map[string]bool, len(inventory))
	seedSets := make([]map[int]bool, len(inventory))
	allSeeds := map[int]bool{}

	r.Sites = make([]SiteCoverage, len(inventory))
	for i, s := range inventory {
		idxBySite[s.Site] = i
		r.Sites[i] = SiteCoverage{Site: s}
		scSets[i] = map[string]bool{}
		scSeed1Sets[i] = map[string]bool{}
		seedSets[i] = map[int]bool{}
	}

	for _, cap := range captures {
		r.PairsIncluded++
		allSeeds[cap.Seed] = true
		if cap.Seed == 1 {
			r.Seed1Included++
		}
		for _, call := range cap.Calls {
			idx, ok := idxBySite[call.Site]
			if !ok {
				continue
			}
			r.Sites[idx].DrawCount++
			r.TotalDraws++
			scSets[idx][cap.Scenario] = true
			seedSets[idx][cap.Seed] = true
			if cap.Seed == 1 {
				r.Sites[idx].Seed1DrawCount++
				r.Seed1Draws++
				scSeed1Sets[idx][cap.Scenario] = true
			}
		}
	}

	for i := range r.Sites {
		r.Sites[i].Scenarios = sortedStrings(scSets[i])
		r.Sites[i].Seed1Scenarios = sortedStrings(scSeed1Sets[i])
		r.Sites[i].Seeds = sortedInts(seedSets[i])
	}
	r.Seeds = sortedInts(allSeeds)
	sort.Slice(r.Exclusions, func(i, j int) bool {
		if r.Exclusions[i].Seed != r.Exclusions[j].Seed {
			return r.Exclusions[i].Seed < r.Exclusions[j].Seed
		}
		return r.Exclusions[i].Scenario < r.Exclusions[j].Scenario
	})
	return r
}

// Totals computes headline counts across all top-level draw sites.
func (r *Report) Totals() Totals {
	t := Totals{
		Sites:      len(r.Sites),
		TotalDraws: r.TotalDraws,
		Seed1Draws: r.Seed1Draws,
	}
	for i := range r.Sites {
		if r.Sites[i].Reached() {
			t.ReachedAll++
		}
		if r.Sites[i].ReachedSeed1() {
			t.ReachedSeed1++
		}
	}
	return t
}

// ByFile groups draw-site reach by C source file, sorted alphabetically.
func (r *Report) ByFile() []FileRollup {
	index := map[string]int{}
	var out []FileRollup
	for i := range r.Sites {
		sc := &r.Sites[i]
		idx, ok := index[sc.Site.File]
		if !ok {
			idx = len(out)
			index[sc.Site.File] = idx
			out = append(out, FileRollup{File: sc.Site.File})
		}
		out[idx].Sites++
		out[idx].Draws += sc.DrawCount
		if sc.Reached() {
			out[idx].ReachedAll++
		}
		if sc.ReachedSeed1() {
			out[idx].ReachedSeed1++
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].File < out[j].File })
	return out
}

// LeastReachedFiles returns files sorted by ascending all-seeds reach percent,
// breaking ties by more total sites first, then file name.
func (r *Report) LeastReachedFiles() []FileRollup {
	rolls := r.ByFile()
	sort.Slice(rolls, func(i, j int) bool {
		pi := pctFloat(rolls[i].ReachedAll, rolls[i].Sites)
		pj := pctFloat(rolls[j].ReachedAll, rolls[j].Sites)
		if pi != pj {
			return pi < pj
		}
		if rolls[i].Sites != rolls[j].Sites {
			return rolls[i].Sites > rolls[j].Sites
		}
		return rolls[i].File < rolls[j].File
	})
	return rolls
}

// Render returns the generated report files keyed by filename.
func (r *Report) Render() map[string]string {
	return map[string]string{
		InventoryFile: r.inventoryTSV(),
		CoverageFile:  r.coverageTSV(),
		SummaryFile:   r.summaryTXT(),
	}
}

// WriteOutputs writes the rendered reports into outDir.
func (r *Report) WriteOutputs(outDir string) error {
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return err
	}
	for name, body := range r.Render() {
		if err := os.WriteFile(filepath.Join(outDir, name), []byte(body), 0o644); err != nil {
			return err
		}
	}
	return nil
}

func (r *Report) inventoryTSV() string {
	var b strings.Builder
	b.WriteString(header)
	b.WriteString("# C RNG draw-primitive call instructions extracted from the compiled reference binary.\n")
	b.WriteString("# columns: site\tfunction\tprimitive\tkind\tcall_vaddr\tret_vaddr\n")
	for i := range r.Sites {
		s := r.Sites[i].Site
		fmt.Fprintf(&b, "%s\t%s\t%s\ttop-level\t0x%x\t0x%x\n",
			s.Site, s.Function, s.Primitive, s.CallVaddr, s.RetVaddr)
	}
	for _, s := range r.InternalCalls {
		fmt.Fprintf(&b, "%s\t%s\t%s\tinternal\t0x%x\t0x%x\n",
			s.Site, s.Function, s.Primitive, s.CallVaddr, s.RetVaddr)
	}
	return b.String()
}

func (r *Report) coverageTSV() string {
	var b strings.Builder
	b.WriteString(header)
	b.WriteString("# Draw-site reach of the C reference binary across verified census captures.\n")
	b.WriteString("# columns: site\tfunction\tprimitive\treached\treached_seed1\tdraw_count\tdraw_count_seed1\tscenario_count\tscenarios\n")
	for i := range r.Sites {
		sc := &r.Sites[i]
		reached := "no"
		if sc.Reached() {
			reached = "yes"
		}
		reachedSeed1 := "no"
		if sc.ReachedSeed1() {
			reachedSeed1 = "yes"
		}
		scenarios := "-"
		if len(sc.Scenarios) > 0 {
			scenarios = formatScenarioList(sc.Scenarios)
		}
		fmt.Fprintf(&b, "%s\t%s\t%s\t%s\t%s\t%d\t%d\t%d\t%s\n",
			sc.Site.Site, sc.Site.Function, sc.Site.Primitive,
			reached, reachedSeed1, sc.DrawCount, sc.Seed1DrawCount,
			len(sc.Scenarios), scenarios)
	}
	return b.String()
}

// formatScenarioList keeps the scenarios column readable and bounded for
// boot-time sites hit by thousands of scenarios while preserving exact lists
// for targeted sites (up to 10 scenarios listed verbatim; larger sets list the
// first 10 plus "+N more").
func formatScenarioList(scenarios []string) string {
	const maxListed = 10
	if len(scenarios) <= maxListed {
		return strings.Join(scenarios, ",")
	}
	return fmt.Sprintf("%s,+%d more", strings.Join(scenarios[:maxListed], ","), len(scenarios)-maxListed)
}

func (r *Report) summaryTXT() string {
	t := r.Totals()
	var b strings.Builder
	b.WriteString(header)
	b.WriteString("# Deterministic: no dates, no paths outside the repository.\n")
	fmt.Fprintf(&b, "pairs included\t%d (seed 1: %d, seeds: %s)\n", r.PairsIncluded, r.Seed1Included, joinInts(r.Seeds))
	fmt.Fprintf(&b, "pairs excluded\t%d\n", len(r.Exclusions))
	fmt.Fprintf(&b, "c draw sites (seed 1)\t%d of %d reached (%s)\n", t.ReachedSeed1, t.Sites, pctStr(t.ReachedSeed1, t.Sites))
	fmt.Fprintf(&b, "c draw sites (all seeds)\t%d of %d reached (%s)\n", t.ReachedAll, t.Sites, pctStr(t.ReachedAll, t.Sites))
	fmt.Fprintf(&b, "multi-seed gain\t+%d sites\n", t.ReachedAll-t.ReachedSeed1)
	fmt.Fprintf(&b, "top-level draws (seed 1)\t%d\n", t.Seed1Draws)
	fmt.Fprintf(&b, "top-level draws (all seeds)\t%d\n", t.TotalDraws)

	b.WriteString("\n[least reached c files]\n")
	b.WriteString("# columns: file\tseed1 reached/total (percent)\tall seeds reached/total (percent)\tdraws\n")
	for _, roll := range r.LeastReachedFiles() {
		fmt.Fprintf(&b, "%s\t%d/%d (%s)\t%d/%d (%s)\t%d\n",
			roll.File,
			roll.ReachedSeed1, roll.Sites, pctStr(roll.ReachedSeed1, roll.Sites),
			roll.ReachedAll, roll.Sites, pctStr(roll.ReachedAll, roll.Sites),
			roll.Draws)
	}

	b.WriteString("\n[per c file]\n")
	b.WriteString("# columns: file\tseed1 reached/total (percent)\tall seeds reached/total (percent)\tdraws\n")
	for _, roll := range r.ByFile() {
		fmt.Fprintf(&b, "%s\t%d/%d (%s)\t%d/%d (%s)\t%d\n",
			roll.File,
			roll.ReachedSeed1, roll.Sites, pctStr(roll.ReachedSeed1, roll.Sites),
			roll.ReachedAll, roll.Sites, pctStr(roll.ReachedAll, roll.Sites),
			roll.Draws)
	}

	b.WriteString("\n[never reached draw sites]\n")
	b.WriteString("# columns: site\tfunction\tprimitive\n")
	for i := range r.Sites {
		sc := &r.Sites[i]
		if !sc.Reached() {
			fmt.Fprintf(&b, "%s\t%s\t%s\n", sc.Site.Site, sc.Site.Function, sc.Site.Primitive)
		}
	}

	if len(r.Exclusions) > 0 {
		b.WriteString("\n[excluded pairs]\n")
		b.WriteString("# columns: seed\tscenario\treason\n")
		for _, ex := range r.Exclusions {
			fmt.Fprintf(&b, "%d\t%s\t%s\n", ex.Seed, ex.Scenario, ex.Reason)
		}
	}
	return b.String()
}

func pctFloat(part, total int) float64 {
	if total == 0 {
		return 0
	}
	return float64(part) * 100 / float64(total)
}

func pctStr(part, total int) string {
	if total == 0 {
		return "n/a"
	}
	return strconv.FormatFloat(pctFloat(part, total), 'f', 1, 64) + "%"
}

func sortedStrings(m map[string]bool) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

func sortedInts(m map[int]bool) []int {
	out := make([]int, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Ints(out)
	return out
}

func joinInts(nums []int) string {
	if len(nums) == 0 {
		return "-"
	}
	parts := make([]string, len(nums))
	for i, n := range nums {
		parts[i] = strconv.Itoa(n)
	}
	return strings.Join(parts, ",")
}
